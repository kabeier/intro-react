#!/usr/bin/env node
// Build the student code repo from the lesson data, so it can never drift from the slides.
//   node tools/build-code-repo.mjs [output folder]        (default ../intro-react-code)
// main and one branch per lecture. A branch holds that lecture's FINISHED code, with one commit per
// feature, and sits on top of the lecture before it. `start` is the create-vite template.
// Commits carry the instructor's name: this repo goes to students.
import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync, copyFileSync, existsSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const Course = require(path.join(ROOT, 'shared/course.js'))
globalThis.Course = Course
for (const f of JSON.parse(readFileSync(path.join(ROOT, 'shared/course/manifest.json'), 'utf8'))) await import(path.join(ROOT, 'shared/course', f))
await import(path.join(ROOT, 'shared/course/code-repo.js'))

// The list the code-repo page uses: which branch each lecture starts from and ends on.
export function lecturesFile(C) {
  const main = C.all().filter((l) => l.label && l.label.startsWith('Unit'))
  const rows = C.all().map((l) => {
    const k = main.indexOf(l)
    const branch = C.codeRepo.branch(l)
    return { id: l.id, label: l.label, title: l.title, branch, start: k < 0 ? 'start-' + branch : k === 0 ? 'start' : C.codeRepo.branch(main[k - 1]), features: l.features.length }
  })
  return '// Generated by tools/build-code-repo.mjs.\nwindow.LECTURES = ' + JSON.stringify(rows, null, 1) + '\n'
}

const OUT = path.resolve(process.argv[2] || path.join(ROOT, '..', 'intro-react-code'))
const repo = Course.codeRepo
const git = (...a) => execFileSync('git', a, { cwd: OUT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim()
const ID = ['-c', 'user.name=kevin beier', '-c', 'user.email=kabeier@gmail.com']

const README = `# intro-react-code

The Pokemon app from the Code Platoon React lectures, one branch per lecture.

**How to use this repo:** https://kabeier.github.io/intro-react/code-repo/

- Each branch holds the code at the **end** of that lecture, with one commit per feature.
- To start a lecture, use the branch of the lecture before it. The page above gives the exact command.
- After you switch branches, run \`npm install\`: each lecture can add packages.
- \`main\` is the finished app. \`start\` is the empty create-vite template.

The step-by-step story of every line is in the [Code Explorer](https://kabeier.github.io/intro-react/explore.html).
`

function writeTree(files, assets) {
  for (const e of readdirSync(OUT)) if (!['.git', 'package-lock.json', 'README.md', 'node_modules'].includes(e)) rmSync(path.join(OUT, e), { recursive: true, force: true })
  for (const [name, text] of Object.entries(files)) { const p = path.join(OUT, name); mkdirSync(path.dirname(p), { recursive: true }); writeFileSync(p, text) }
  for (const [name, src] of Object.entries(assets)) { const p = path.join(OUT, name); mkdirSync(path.dirname(p), { recursive: true }); copyFileSync(path.join(ROOT, src), p) }
  writeFileSync(path.join(OUT, 'README.md'), README)
}
let lastPkg = null
function commit(message, files, assets) {
  writeTree(files, assets)
  if (files['package.json'] !== lastPkg) {
    lastPkg = files['package.json']
    rmSync(path.join(OUT, 'package-lock.json'), { force: true })
    execFileSync('npm', ['install', '--package-lock-only', '--ignore-scripts', '--no-audit', '--no-fund', '--loglevel=error'], { cwd: OUT, stdio: 'pipe' })
  }
  git('add', '-A')
  git(...ID, 'commit', '-q', '-m', message)
  return git('rev-parse', 'HEAD')
}

rmSync(OUT, { recursive: true, force: true })
mkdirSync(OUT, { recursive: true })
git('init', '-q', '-b', 'main')

const main = Course.all().filter((l) => l.label && l.label.startsWith('Unit'))
const first = main[0]
commit('Start: the create-vite template', Course.filesAt(first, null), Course.assetsOf(first))
git('branch', 'start')

const atFeature = {}
for (const l of main) {
  const short = l.label.replace(' · ', ' ')
  for (const [k, f] of l.features.entries()) {
    atFeature[l.id + ':' + f.id] = commit(`${short}, feature ${k + 1}: ${f.title}`, Course.checkpoint(l, f.id), Course.assetsOf(l))
  }
  git('branch', repo.branch(l))
  console.log(repo.branch(l), git('rev-parse', '--short', 'HEAD'))
}

// Optional lessons branch off the commit they start from.
for (const l of Course.all().filter((x) => !main.includes(x))) {
  git('branch', 'start-' + repo.branch(l), atFeature[l.base.lesson + ':' + l.base.feature])
  git('switch', '-q', '-c', repo.branch(l), atFeature[l.base.lesson + ':' + l.base.feature])
  lastPkg = Course.checkpoint(Course.get(l.base.lesson), l.base.feature)['package.json']
  for (const [k, f] of l.features.entries()) commit(`Optional, feature ${k + 1}: ${f.title}`, Course.checkpoint(l, f.id), Course.assetsOf(l))
  console.log(repo.branch(l), git('rev-parse', '--short', 'HEAD'))
  git('switch', '-q', 'main')
}
writeFileSync(path.join(ROOT, 'code-repo/lectures.js'), lecturesFile(Course))
console.log('branches', git('branch', '--format=%(refname:short)').split('\n').length, 'commits on main', git('rev-list', '--count', 'main'))
